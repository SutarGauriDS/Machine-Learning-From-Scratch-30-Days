# ============================================================
# DAY 24 — MODEL EVALUATION
# Classification Model Evaluation using Multiple Metrics
# ============================================================

import pandas as pd
import matplotlib.pyplot as plt

from sklearn.datasets import load_breast_cancer
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
    roc_curve,
    roc_auc_score,
    ConfusionMatrixDisplay
)


# ============================================================
# 1. Load Dataset
# ============================================================

data = load_breast_cancer()

X = pd.DataFrame(
    data.data,
    columns=data.feature_names
)

y = pd.Series(
    data.target,
    name="target"
)

print("=" * 60)
print("DAY 24 — MODEL EVALUATION")
print("=" * 60)

print("\nDataset Shape:", X.shape)
print("Target Classes:", data.target_names)


# ============================================================
# 2. Train-Test Split
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nTraining Samples:", X_train.shape[0])
print("Testing Samples :", X_test.shape[0])


# ============================================================
# 3. Create Random Forest Model
# ============================================================
model = RandomForestClassifier(
    n_estimators=100,
    random_state=42
)
# ============================================================
# 4. Train Model
# ============================================================
model.fit(X_train, y_train)

print("\nModel Training Completed!")

# ============================================================
# 5. Make Predictions
# ============================================================
y_pred = model.predict(X_test)

# Probability of positive class
y_probability = model.predict_proba(X_test)[:, 1]

# ============================================================
# 6. Calculate Evaluation Metrics
# ============================================================

accuracy = accuracy_score(y_test, y_pred)

precision = precision_score(
    y_test,
    y_pred,
    zero_division=0
)

recall = recall_score(
    y_test,
    y_pred,
    zero_division=0
)

f1 = f1_score(
    y_test,
    y_pred,
    zero_division=0
)

roc_auc = roc_auc_score(
    y_test,
    y_probability
)


# ============================================================
# 7. Display Metrics
# ============================================================

print("\n" + "=" * 60)
print("MODEL EVALUATION METRICS")
print("=" * 60)

print(f"\nAccuracy  : {accuracy:.4f}")
print(f"Precision : {precision:.4f}")
print(f"Recall    : {recall:.4f}")
print(f"F1-Score  : {f1:.4f}")
print(f"ROC-AUC   : {roc_auc:.4f}")


# ============================================================
# 8. Confusion Matrix
# ============================================================

cm = confusion_matrix(
    y_test,
    y_pred
)

print("\n" + "=" * 60)
print("CONFUSION MATRIX")
print("=" * 60)

print(cm)

print("\nConfusion Matrix:")
print("TN =", cm[0, 0])
print("FP =", cm[0, 1])
print("FN =", cm[1, 0])
print("TP =", cm[1, 1])


# ============================================================
# 9. Classification Report
# ============================================================

print("\n" + "=" * 60)
print("CLASSIFICATION REPORT")
print("=" * 60)

print(
    classification_report(
        y_test,
        y_pred,
        target_names=data.target_names,
        zero_division=0
    )
)


# ============================================================
# 10. Visualize Confusion Matrix
# ============================================================

ConfusionMatrixDisplay.from_predictions(
    y_test,
    y_pred,
    display_labels=data.target_names
)

plt.title("Random Forest - Confusion Matrix")
plt.tight_layout()
plt.show()


# ============================================================
# 11. ROC Curve
# ============================================================

fpr, tpr, thresholds = roc_curve(
    y_test,
    y_probability
)

plt.figure(figsize=(5, 3))

plt.plot(
    fpr,
    tpr,
    label=f"Random Forest (AUC = {roc_auc:.4f})"
)

plt.plot(
    [0, 1],
    [0, 1],
    linestyle="--",
    label="Random Classifier"
)

plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")

plt.title("ROC Curve")

plt.legend()

plt.tight_layout()
plt.show()


# ============================================================
# 12. Feature Importance
# ============================================================

feature_importance = pd.DataFrame({
    "Feature": X.columns,
    "Importance": model.feature_importances_
})

feature_importance = feature_importance.sort_values(
    by="Importance",
    ascending=False
)

print("\n" + "=" * 60)
print("TOP 10 IMPORTANT FEATURES")
print("=" * 60)

print(
    feature_importance.head(10).to_string(
        index=False
    )
)


# ============================================================
# 13. Visualize Top 10 Feature Importance
# ============================================================

top_features = feature_importance.head(10)

plt.figure(figsize=(5, 4))

plt.barh(
    top_features["Feature"][::-1],
    top_features["Importance"][::-1]
)

plt.xlabel("Importance")
plt.ylabel("Feature")
plt.title("Top 10 Feature Importance")

plt.tight_layout()
plt.show()


# ============================================================
# 14. Create Evaluation Summary
# ============================================================

evaluation_results = pd.DataFrame({
    "Metric": [
        "Accuracy",
        "Precision",
        "Recall",
        "F1-Score",
        "ROC-AUC"
    ],
    "Score": [
        accuracy,
        precision,
        recall,
        f1,
        roc_auc
    ]
})

print("\n" + "=" * 60)
print("FINAL EVALUATION SUMMARY")
print("=" * 60)

print(evaluation_results.to_string(index=False))


# ============================================================
# 15. Save Results
# ============================================================

evaluation_results.to_csv(
    "Day24_Model_Evaluation_Results.csv",
    index=False
)

feature_importance.to_csv(
    "Day24_Feature_Importance.csv",
    index=False
)

print("\nResults saved successfully:")
print("- Day24_Model_Evaluation_Results.csv")
print("- Day24_Feature_Importance.csv")


